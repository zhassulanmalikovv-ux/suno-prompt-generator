def t(value):
    """Look up editorial copy. Never translate user content or call a service."""
    if not isinstance(value, str):
        return value
    if value.startswith("<") or ("<div" in value):
        return markup(value)
    if value.startswith("**") and value.endswith("**"):
        return "**" + t(value[2:-2]) + "**"
    text = " ".join(value.split()) if "\n" in value or "\r" in value else value.strip()
    record = COPY.get(value) or COPY.get(text)
    if record is None:
        return value
    translated = record[locale()]
    if value == text:
        return translated
    if value in COPY:
        return translated
    return value[:len(value)-len(value.lstrip())] + translated + value[len(value.rstrip()):]

